    quantity INT NOT NULL,
    unit_price DOUBLE NOT NULL,
    total_price DOUBLE NOT NULL,
    note LONGTEXT DEFAULT NULL,
    created_at DATETIME NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    paid TINYINT(1) NOT NULL,
    archived_at DATETIME DEFAULT NULL,
    INDEX IDX_E665A4F6A76ED395 (user_id),
    INDEX IDX_E665A4F6700047D2 (ticket_id),
    PRIMARY KEY (id),
    CONSTRAINT FK_E665A4F6A76ED395 FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT FK_E665A4F6700047D2 FOREIGN KEY (ticket_id) REFERENCES ticket (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

